# Strong but mathematically identical Stage-2 site formulation
# ---------------------------------------------------------------------------

def solve_fixed_capacity_assignment_strong(
    instance,
    durations,
    costs,
    turnover: float,
    solver_config: SolverConfig,
    *,
    warm_start: ScheduleColumn | None = None,
    symmetry_breaking: bool = True,
) -> FixedCapacityResult:
    """Stage-2-only exact reformulation with stronger occupation linking."""
    import gurobipy as gp
    from gurobipy import GRB

    d = np.asarray(durations, dtype=float)
    if d.shape != (instance.num_cases,) or not np.all(np.isfinite(d)) or np.any(d < 0):
        raise ValueError("Durations must be finite and nonnegative with one value per case")
    if not np.isfinite(turnover) or turnover < 0:
        raise ValueError("Turnover must be finite and nonnegative")
    blocks = {b.id: b for b in instance.calendar.candidates}
    if len(blocks) != len(instance.calendar.candidates):
        raise ValueError("Duplicate roster block IDs")
    for b in blocks.values():
        if (
            not b.is_fixed
            or b.activation_cost != 0
            or not np.isfinite(b.capacity_minutes)
            or b.capacity_minutes <= 0
        ):
            raise ValueError("Every roster block must have fixed positive capacity and zero activation cost")
    eligible: dict[int, list[BlockId]] = {}
    for i, case in enumerate(instance.cases):
        bids = sorted(set(instance.case_eligible_blocks.get(i, [])))
        if not bids:
            raise CapacityModelError(
                f"Case {case.case_id} has no eligible allocated block at site {case.site!r}"
            )
        if any(bid not in blocks or bid.site != case.site for bid in bids):
            raise CapacityModelError(
                f"Case {case.case_id} has a missing or cross-site eligible block"
            )
        eligible[i] = bids

    k = costs.idle_per_minute * (
        sum(b.capacity_minutes for b in blocks.values())
        - float(d.sum())
        - float(turnover) * len(d)
    )
    groups = interchangeable_block_groups(instance) if symmetry_breaking else []

    with gp.Model("fixed_capacity_psi_strong_stage2") as model:
        _apply_solver_params(model, solver_config)
        x = {
            (i, bid): model.addVar(vtype=GRB.BINARY, name=f"x[{i},{j}]")
            for i, bids in eligible.items()
            for j, bid in enumerate(bids)
        }
        # Exact at every integer x solution, but continuous in the relaxation.
        u = {
            bid: model.addVar(lb=0.0, ub=1.0, vtype=GRB.CONTINUOUS, name=f"u[{j}]")
            for j, bid in enumerate(blocks)
        }
        block_cases = {bid: [] for bid in blocks}
        for i, bid in x:
            block_cases[bid].append(i)

        for i, bids in eligible.items():
            model.addConstr(gp.quicksum(x[i, bid] for bid in bids) == 1, name=f"assign[{i}]")

        ots = []
        for j, (bid, block) in enumerate(blocks.items()):
            ids = block_cases[bid]
            count = gp.quicksum(x[i, bid] for i in ids)
            # Strong exact occupation hull for integer x.
            for i in ids:
                model.addConstr(x[i, bid] <= u[bid], name=f"occupy_link[{j},{i}]")
            model.addConstr(u[bid] <= count, name=f"occupation_upper[{j}]")
            load = gp.quicksum(float(d[i]) * x[i, bid] for i in ids) + float(turnover) * (
                count - u[bid]
            )
            ot = model.addVar(lb=0.0, name=f"ot[{j}]")
            model.addConstr(ot >= load - float(block.capacity_minutes), name=f"overtime[{j}]")
            ots.append(ot)

        for group in groups:
            for left, right in zip(group, group[1:]):
                model.addConstr(u[left] >= u[right])
                prefix = gp.LinExpr()
                for i in block_cases[left]:
                    model.addConstr(x[i, right] <= prefix)
                    prefix = prefix + x[i, left]

        objective = (
            float(costs.overtime_per_minute + costs.idle_per_minute) * gp.quicksum(ots)
            + float(costs.idle_per_minute * turnover) * gp.quicksum(u.values())
        )
        model.setObjective(objective, GRB.MINIMIZE)

        if warm_start is not None:
            schedule_metrics(warm_start, d, costs, turnover)
            assignment = {
                i: bid for (i, bid), value in warm_start.z_assign.items() if value > 0.5
            }
            column_from_assignment(instance, assignment)
            for group in groups:
                ordered = sorted(
                    group,
                    key=lambda bid: min(
                        (i for i, b in assignment.items() if b == bid),
                        default=instance.num_cases,
                    ),
                )
                rename = dict(zip(ordered, group))
                assignment = {i: rename.get(bid, bid) for i, bid in assignment.items()}
            for (i, bid), var in x.items():
                var.Start = float(assignment[i] == bid)
            occupied = set(assignment.values())
            for bid, var in u.items():
                var.Start = float(bid in occupied)

        model.optimize()
        diagnostics = diagnostics_from_model(model)
        column = metrics = None
        if diagnostics.sol_count:
            assignment = {i: bid for (i, bid), var in x.items() if var.X > 0.5}
            column = column_from_assignment(instance, assignment)
            metrics = schedule_metrics(column, d, costs, turnover)
        return FixedCapacityResult(
            column=column,
            diagnostics=diagnostics,
            objective_mode="psi",
            K=float(k),
            metrics=metrics,
            symmetry_groups=len(groups),
        )


def _strong_week_worker(
    week,
    durations: np.ndarray,
    warm: ScheduleColumn | None,
    s,
    *,
    work_limit: float,
    wall_seconds: int,
    mip_gap: float,
    seed: int,
    label: str,
    log_root: str,
) -> base.PlanResult:
    """Solve one pooled week; the global parent pool handles cross-map parallelism."""
    final.install_final_adapter()
    fixes.apply_runtime_fixes()
    science.apply_scientific_fixes()
    protocol.install_numeric_policy()

    d = np.asarray(durations, dtype=float)
    t0 = time.perf_counter()
    parts = []
    solver_phi_ub = phi_lb = solver_psi_ub = psi_lb = 0.0
    statuses: list[str] = []
    all_optimal = True

    initial_wall = max(
        int(wall_seconds),
        int(math.ceil(hardening.EMERGENCY_WALL_TO_WORK_MULTIPLIER * float(work_limit))),
    )
    for site in final.PRIMARY_SITES:
        view = final._site_view(week, site)
        local_d = d[view.global_indices]
        local_warm = final._localize_warm(warm, view)
        site_dir = Path(log_root) / _safe_name(label) / f"week_{int(week.position):03d}"
        site_dir.mkdir(parents=True, exist_ok=True)

        def one(limit: int, start: ScheduleColumn | None, suffix: str):
            cfg = SolverConfig(
                time_limit_seconds=max(1, int(limit)),
                work_limit=float(work_limit),
                mip_gap=max(0.0, float(mip_gap)),
                threads=1,
                verbose=bool(s.verbose),
                mip_gap_abs=1e-10,
                seed=int(seed),
                log_file=str(site_dir / f"{_safe_name(site)}_{suffix}.log"),
            )
            return solve_fixed_capacity_assignment_strong(
                view.instance,
                local_d,
                final.final_cost_cfg(s),
                float(final.PRIMARY_TURNOVER),
                cfg,
                warm_start=start,
                symmetry_breaking=True,
            )

        result = one(initial_wall, local_warm, "initial")
        if result.column is None or any(
            x is None for x in (result.phi_ub, result.phi_lb, result.psi_ub, result.psi_lb)
        ):
            raise RuntimeError(
                f"Week {week.position} {label} {site}: no incumbent/bound "
                f"({result.diagnostics.status})"
            )

        if result.diagnostics.status == "TIME_LIMIT":
            retry_wall = max(
                initial_wall + 1,
                int(math.ceil(initial_wall * hardening.EMERGENCY_RETRY_MULTIPLIER)),
            )
            base.LOG.warning(
                "[MATRIX] week=%s site=%s %s wall cap %ss fired; retrying with %ss",
                week.position,
                site,
                label,
                initial_wall,
                retry_wall,
            )
            retry = one(retry_wall, result.column, "retry")
            if retry.column is None or any(
                x is None for x in (retry.phi_ub, retry.phi_lb, retry.psi_ub, retry.psi_lb)
            ):
                raise RuntimeError(
                    f"Week {week.position} {label} {site}: retry returned no incumbent/bound"
                )
            result = retry
            if result.diagnostics.status == "TIME_LIMIT":
                base.LOG.warning(
                    "[MATRIX-WARN] week=%s site=%s %s wall cap fired twice; "
                    "keeping valid incumbent/bound",
                    week.position,
                    site,
                    label,
                )

        parts.append((view, result.column))
        solver_phi_ub += float(result.phi_ub)
        phi_lb += float(result.phi_lb)
        solver_psi_ub += float(result.psi_ub)
        psi_lb += float(result.psi_lb)
        statuses.append(f"{site}:{result.diagnostics.status}")
        all_optimal = all_optimal and bool(result.diagnostics.proven_optimal)

    column = final._merge_site_columns(week.instance, parts)
    recomputed_phi = float(
        schedule_metrics(column, d, final.final_cost_cfg(s), final.PRIMARY_TURNOVER)["phi"]
    )
    numeric.assert_phi_accounting_close(
        recomputed_phi,
        solver_phi_ub,
        context=f"Matrix deterministic week {week.position} {label}",
    )
    gap = numeric._accounted_native_gap(
        week,
        d,
        s,
        turnover=float(final.PRIMARY_TURNOVER),
        recomputed_phi_ub=recomputed_phi,
        psi_lb=psi_lb,
    )
    return base.PlanResult(
        week=int(week.position),
        column=column,
        objective=recomputed_phi,
        bound=float(phi_lb),
        gap=float(gap),
        status="OPTIMAL" if all_optimal else "|".join(statuses),
        solve_seconds=time.perf_counter() - t0,
        exact=bool(all_optimal and abs(solver_psi_ub - psi_lb) <= 1e-6),
        tiebreak_used=False,
    )


