def _save_plan_checkpoint(
    path: Path,
    *,
    kind: str,
    map_hash: str,
    week,
    durations: np.ndarray,
    plan: base.PlanResult,
    s,
    seal_sha256: str,
    warm_parent_hash: str | None,
) -> None:
    feasible = float(
        plan.column.compute_cost(
            np.asarray(durations, float), final.final_cost_cfg(s), final.PRIMARY_TURNOVER
        )
    )
    numeric.assert_phi_accounting_close(
        feasible, float(plan.objective), context=f"matrix-cache {kind} week {week.position}"
    )
    if float(plan.bound) > feasible + numeric.phi_accounting_tolerance(feasible, plan.bound):
        raise RuntimeError(f"Matrix cache {kind} week {week.position}: lower bound exceeds incumbent")
    payload = {
        "engine_version": ENGINE_VERSION,
        "seal_sha256": seal_sha256,
        "amendment_sha256": protocol.amendment_hash(),
        "git_head": protocol.git_head(),
        "kind": str(kind),
        "map_hash": str(map_hash),
        "week": int(week.position),
        "week_structure_sha256": _week_structure_hash(week),
        "duration_sha256": _duration_hash(np.asarray(durations, float)),
        "solver_protocol": _solver_protocol(s),
        "warm_parent_hash": warm_parent_hash,
        "n_cases": int(plan.column.n_cases),
        "assignment": _assignment_payload(plan.column),
        "objective_phi": feasible,
        "bound_phi": float(plan.bound),
        "gap_native_psi": float(plan.gap),
        "status": str(plan.status),
        "solve_seconds": float(plan.solve_seconds),
        "exact": bool(plan.exact),
        "tiebreak_used": bool(plan.tiebreak_used),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with gzip.open(tmp, "wt", encoding="utf-8") as fh:
        json.dump(payload, fh, sort_keys=True)
    os.replace(tmp, path)


def _load_plan_checkpoint(
    path: Path,
    *,
    kind: str,
    map_hash: str,
    week,
    durations: np.ndarray,
    s,
    seal_sha256: str,
) -> base.PlanResult | None:
    path = Path(path)
    if not path.exists():
        return None
    try:
        with gzip.open(path, "rt", encoding="utf-8") as fh:
            payload = json.load(fh)
        expected = {
            "engine_version": ENGINE_VERSION,
            "seal_sha256": seal_sha256,
            "amendment_sha256": protocol.amendment_hash(),
            "git_head": protocol.git_head(),
            "kind": str(kind),
            "map_hash": str(map_hash),
            "week": int(week.position),
            "week_structure_sha256": _week_structure_hash(week),
            "duration_sha256": _duration_hash(np.asarray(durations, float)),
            "solver_protocol": _solver_protocol(s),
        }
        for key, value in expected.items():
            if payload.get(key) != value:
                raise RuntimeError(f"checkpoint provenance mismatch at {key}")
        column = _column_from_payload(week, payload["assignment"])
        feasible = float(
            column.compute_cost(
                np.asarray(durations, float), final.final_cost_cfg(s), final.PRIMARY_TURNOVER
            )
        )
        numeric.assert_phi_accounting_close(
            feasible,
            float(payload["objective_phi"]),
            context=f"matrix-cache load {kind} week {week.position}",
        )
        bound = float(payload["bound_phi"])
        if bound > feasible + numeric.phi_accounting_tolerance(feasible, bound):
            raise RuntimeError("checkpoint lower bound exceeds recomputed incumbent")
        return base.PlanResult(
            week=int(week.position),
            column=column,
            objective=feasible,
            bound=bound,
            gap=float(payload["gap_native_psi"]),
            status=f"CACHED[{payload['status']}]",
            solve_seconds=float(payload["solve_seconds"]),
            exact=bool(payload["exact"]),
            tiebreak_used=bool(payload.get("tiebreak_used", False)),
        )
    except Exception as exc:
        # A derived checkpoint is never authoritative. Quarantine it and recompute
        # the one affected job rather than discarding the rest of the long run.
        bad = path.with_suffix(path.suffix + f".invalid_{int(time.time())}")
        try:
            os.replace(path, bad)
        except OSError:
            pass
        base.LOG.warning(
            "[MATRIX-CACHE] invalid checkpoint %s quarantined; recomputing (%s)",
            path,
            exc,
        )
        return None


