def _json(path: Path) -> dict[str, Any]:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(dict(payload), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def _canonical_hash(payload: Any) -> str:
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def _safe_name(value: object) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", str(value)).strip("._")[:100] or "unnamed"


def _duration_hash(values: np.ndarray) -> str:
    arr = np.asarray(values, dtype=np.float64)
    return hashlib.sha256(arr.tobytes(order="C")).hexdigest()


def duration_map_hash(weeks: Sequence[Any], duration_by_week: Mapping[int, np.ndarray]) -> str:
    rows = []
    for w in sorted(weeks, key=lambda z: int(z.position)):
        d = np.asarray(duration_by_week[int(w.position)], dtype=np.float64)
        if len(d) != w.instance.num_cases:
            raise RuntimeError(f"Duration vector length changed for week {w.position}")
        rows.append(
            {
                "week": int(w.position),
                "case_ids": [str(c.case_id) for c in w.instance.cases],
                "duration_sha256": _duration_hash(d),
            }
        )
    return _canonical_hash(rows)


def _week_structure_hash(week) -> str:
    payload = {
        "week": int(week.position),
        "start": str(week.start.date()),
        "case_ids": [str(c.case_id) for c in week.instance.cases],
        "blocks": [
            [int(b.id.day_index), str(b.id.site), str(b.id.room), float(b.capacity_minutes)]
            for b in week.instance.calendar.candidates
        ],
        "eligibility": [
            [
                [int(b.day_index), str(b.site), str(b.room)]
                for b in week.instance.case_eligible_blocks.get(i, [])
            ]
            for i in range(week.instance.num_cases)
        ],
    }
    return _canonical_hash(payload)


def _assignment_payload(column: ScheduleColumn) -> list[list[Any]]:
    out: list[list[Any]] = []
    for i in range(column.n_cases):
        bids = [
            bid
            for (j, bid), value in column.z_assign.items()
            if int(j) == i and float(value) > 0.5
        ]
        if len(bids) != 1:
            raise RuntimeError(f"Case {i} is not assigned exactly once")
        bid = bids[0]
        out.append([int(bid.day_index), str(bid.site), str(bid.room)])
    return out


def _column_from_payload(week, values: Sequence[Sequence[Any]]) -> ScheduleColumn:
    if len(values) != week.instance.num_cases:
        raise RuntimeError("Cached assignment length differs from current week")
    assignment = {
        i: BlockId(int(v[0]), str(v[1]), str(v[2]))
        for i, v in enumerate(values)
    }
    return column_from_assignment(week.instance, assignment, enforce_eligibility=True)


