def _load_batch_from_checkpoints(
    matrix_root: Path,
    weeks,
    dm,
    s,
    *,
    map_hash: str,
    kind: str,
    seal_sha256: str,
) -> dict[int, base.PlanResult] | None:
    out = {}
    for week in weeks:
        path = (
            _oracle_week_path(matrix_root, week.position)
            if kind == "oracle"
            else _cache_week_path(matrix_root, map_hash, week.position)
        )
        plan = _load_plan_checkpoint(
            path,
            kind=kind,
            map_hash=map_hash,
            week=week,
            durations=np.asarray(dm[int(week.position)], float),
            s=s,
            seal_sha256=seal_sha256,
        )
        if plan is None:
            return None
        out[int(week.position)] = plan
    return out


def _solve_map_phase(
    matrix_root: Path,
    weeks,
    unique_maps,
    meta,
    s,
    *,
    phase: int,
    seal_sha256: str,
) -> dict[str, dict[int, base.PlanResult]]:
    """Solve all missing week/map jobs in one shared worker pool."""
    phase_hashes = sorted(
        [h for h, row in meta.items() if int(row["phase"]) == int(phase)]
    )
    results: dict[str, dict[int, base.PlanResult]] = {}
    lookup = {int(w.position): w for w in weeks}
    work = float(protocol.load_registry()["evaluation_protocol"]["work_limit_per_site"])
    gap = float(protocol.load_registry()["evaluation_protocol"]["mip_gap"])
    seed = int(protocol.load_registry()["evaluation_protocol"]["seed"])
    wall = max(
        int(s.final_planner_seconds),
        int(math.ceil(hardening.EMERGENCY_WALL_TO_WORK_MULTIPLIER * work)),
    )

    tasks = []
    for h in phase_hashes:
        dm = unique_maps[h]
        results[h] = {}
        parent_hash = meta[h].get("parent_hash")
        parent_plans = None
        if parent_hash is not None:
            parent_dm = unique_maps[parent_hash]
            parent_plans = _load_batch_from_checkpoints(
                matrix_root,
                weeks,
                parent_dm,
                s,
                map_hash=parent_hash,
                kind="plan",
                seal_sha256=seal_sha256,
            )
            if parent_plans is None:
                raise RuntimeError(
                    f"Warm parent {parent_hash} is incomplete before phase {phase}"
                )
        for week in weeks:
            cached = _load_plan_checkpoint(
                _cache_week_path(matrix_root, h, week.position),
                kind="plan",
                map_hash=h,
                week=week,
                durations=np.asarray(dm[int(week.position)], float),
                s=s,
                seal_sha256=seal_sha256,
            )
            if cached is not None:
                results[h][int(week.position)] = cached
                continue
            warm = None if parent_plans is None else parent_plans[int(week.position)].column
            tasks.append((h, week, np.asarray(dm[int(week.position)], float), warm))

    if not tasks:
        return results

    workers = min(int(s.cores), len(tasks))
    base.LOG.info(
        "[MATRIX] phase=%d unique_maps=%d missing_week_jobs=%d workers=%d",
        phase,
        len(phase_hashes),
        len(tasks),
        workers,
    )
    t0 = time.perf_counter()
    with ProcessPoolExecutor(max_workers=workers) as ex:
        futures = {}
        for h, week, d, warm in tasks:
            label = f"phase{phase}_{h[:12]}"
            fut = ex.submit(
                _strong_week_worker,
                week,
                d,
                warm,
                s,
                work_limit=work,
                wall_seconds=wall,
                mip_gap=gap,
                seed=seed,
                label=label,
                log_root=str(Path(matrix_root) / "gurobi_logs"),
            )
            futures[fut] = (h, week, d)

        completed = 0
        for fut in as_completed(futures):
            h, week, d = futures[fut]
            plan = fut.result()
            results[h][int(week.position)] = plan
            _save_plan_checkpoint(
                _cache_week_path(matrix_root, h, week.position),
                kind="plan",
                map_hash=h,
                week=week,
                durations=d,
                plan=plan,
                s=s,
                seal_sha256=seal_sha256,
                warm_parent_hash=meta[h].get("parent_hash"),
            )
            completed += 1
            if completed == 1 or completed % 25 == 0 or completed == len(tasks):
                elapsed = (time.perf_counter() - t0) / 60.0
                base.LOG.info(
                    "[MATRIX] phase=%d %d/%d week-jobs checkpointed | elapsed=%.1f min",
                    phase,
                    completed,
                    len(tasks),
                    elapsed,
                )
    return results


def _precompute_oracle(
    matrix_root: Path,
    weeks,
    arrays,
    s,
    *,
    seal_sha256: str,
) -> dict[int, base.PlanResult]:
    dm = {
        int(wk): np.asarray(arrays.actual[idx], float)
        for wk, idx in arrays.week_slices.items()
    }
    map_hash = duration_map_hash(weeks, dm)
    out: dict[int, base.PlanResult] = {}
    missing = []
    for week in weeks:
        plan = _load_plan_checkpoint(
            _oracle_week_path(matrix_root, week.position),
            kind="oracle",
            map_hash=map_hash,
            week=week,
            durations=dm[int(week.position)],
            s=s,
            seal_sha256=seal_sha256,
        )
        if plan is None:
            missing.append(week)
        else:
            out[int(week.position)] = plan
    if missing:
        base.LOG.info("[MATRIX] oracle missing weeks=%d; solving once for experiment", len(missing))
        subset = {int(w.position): dm[int(w.position)] for w in missing}
        solved = fixes.safe_solve_oracle_batch(
            missing,
            subset,
            s,
            label="oracle_holdout_matrix_precompute",
        )
        for week in missing:
            plan = solved[int(week.position)]
            out[int(week.position)] = plan
            _save_plan_checkpoint(
                _oracle_week_path(matrix_root, week.position),
                kind="oracle",
                map_hash=map_hash,
                week=week,
                durations=dm[int(week.position)],
                plan=plan,
                s=s,
                seal_sha256=seal_sha256,
                warm_parent_hash=None,
            )
    return out


def _precompute(
    matrix_root: Path,
    weeks,
    arrays,
    training_roots: Mapping[str, Path],
    s,
    *,
    seal_sha256: str,
) -> dict[str, Any]:
    unique, meta, aliases = build_duration_registry(
        weeks, arrays, training_roots, s
    )
    booked_hash = aliases["BOOKED"]

    started = time.perf_counter()
    # Phase 0 is only BOOKED. It becomes the common predecision warm start.
    _solve_map_phase(
        matrix_root, weeks, unique, meta, s, phase=0, seal_sha256=seal_sha256
    )
    # Realized oracle is behavior/policy independent and solved once.
    _precompute_oracle(matrix_root, weeks, arrays, s, seal_sha256=seal_sha256)
    # Diagonal policies + projected response benchmarks.
    _solve_map_phase(
        matrix_root, weeks, unique, meta, s, phase=1, seal_sha256=seal_sha256
    )
    # Off-diagonal response conditions warm-start from their own diagonal plan.
    _solve_map_phase(
        matrix_root, weeks, unique, meta, s, phase=2, seal_sha256=seal_sha256
    )

    total_aliases = len(aliases)
    total_unique = len(unique)
    payload = {
        "status": "PRECOMPUTE_COMPLETE",
        "engine_version": ENGINE_VERSION,
        "seal_sha256": seal_sha256,
        "amendment_sha256": protocol.amendment_hash(),
        "git_head": protocol.git_head(),
        "booked_map_hash": booked_hash,
        "total_requested_duration_maps": total_aliases,
        "unique_duration_maps": total_unique,
        "exact_deduplications": total_aliases - total_unique,
        "holdout_weeks": len(weeks),
        "requested_week_jobs_before_dedup": total_aliases * len(weeks),
        "unique_week_jobs_after_dedup": total_unique * len(weeks),
        "aliases": aliases,
        "map_metadata": meta,
        "solver_protocol": _solver_protocol(s),
        "elapsed_seconds": time.perf_counter() - started,
    }
    _write_json(Path(matrix_root) / PRECOMPUTE_STATUS, payload)
    return payload


