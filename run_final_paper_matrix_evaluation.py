def _materialize_holdout(primary_root: Path, s):
    cfg = base.build_config(s)
    df = base.load_data(cfg)
    scoped, scope_summary = base.apply_experiment_scope(df, cfg)
    if len(scoped) != science.EXPECTED_SCOPED_CASES:
        raise RuntimeError(
            f"Scoped cohort changed: {len(scoped)} != {science.EXPECTED_SCOPED_CASES}"
        )
    train_starts, hold_starts, split_audit = base.choose_split(scoped, s)
    ws = base.week_start_series(scoped)
    train_count = int(ws.isin(train_starts).sum())
    hold_count = int(ws.isin(hold_starts).sum())
    if train_count != science.EXPECTED_TRAIN_CASES or hold_count != science.EXPECTED_HOLDOUT_CASES:
        raise RuntimeError(f"Evaluation split changed: train={train_count}, holdout={hold_count}")
    hold_df = scoped[ws.isin(hold_starts)].copy()
    hold_sites = {
        str(k): int(v)
        for k, v in hold_df[base.Col.SITE].value_counts().to_dict().items()
    }
    if hold_sites != science.EXPECTED_HOLDOUT_SITE_COUNTS:
        raise RuntimeError(f"Holdout site counts changed: {hold_sites}")

    hold_start = min(hold_starts)
    hist = scoped[ws < hold_start].copy()
    pools = base.build_candidate_pools(hist, cfg)
    elig = base.build_eligibility_maps(hist, cfg)
    hold_weeks = base.build_bundles(
        scoped,
        hold_starts,
        cfg=cfg,
        candidate_pools=pools,
        eligibility_maps=elig,
        offset=s.train_weeks,
    )
    enc = science.ScientificFeatureEncoder.from_manifest(
        _json(primary_root / "FEATURE_MANIFEST.json")
    )
    hold_a = base.build_arrays(hold_weeks, enc)
    if hold_a.p != science.EXPECTED_FEATURES:
        raise RuntimeError("Holdout feature dimension differs from frozen training encoder")
    return hold_weeks, hold_a, scope_summary, split_audit


def _load_policies(training_root: Path) -> dict[str, np.ndarray]:
    policy_file = np.load(training_root / "POLICIES.npz")
    out = {name: np.asarray(policy_file[name], float) for name in METHODS}
    for name, w in out.items():
        if w.shape != (science.EXPECTED_FEATURES,):
            raise RuntimeError(f"Frozen policy {name} has unexpected shape {w.shape}")
    return out


def build_duration_registry(
    weeks,
    arrays,
    training_roots: Mapping[str, Path],
    s,
) -> tuple[
    dict[str, dict[int, np.ndarray]],
    dict[str, dict[str, Any]],
    dict[str, str],
]:
    """Return unique duration maps, metadata, and alias->map-hash."""
    unique: dict[str, dict[int, np.ndarray]] = {}
    meta: dict[str, dict[str, Any]] = {}
    alias_to_hash: dict[str, str] = {}

    def add(alias: str, dm: Mapping[int, np.ndarray], *, phase: int, parent: str | None):
        normalized = {int(k): np.asarray(v, dtype=float).copy() for k, v in dm.items()}
        h = duration_map_hash(weeks, normalized)
        alias_to_hash[alias] = h
        if h not in unique:
            unique[h] = normalized
            meta[h] = {
                "phase": int(phase),
                "parent_alias": parent,
                "aliases": [alias],
            }
        else:
            meta[h]["phase"] = min(int(meta[h]["phase"]), int(phase))
            meta[h]["aliases"].append(alias)
            if meta[h].get("parent_alias") is None and parent is not None:
                meta[h]["parent_alias"] = parent
        return h

    booked_dm = {
        int(wk): np.asarray(arrays.booked[idx], float)
        for wk, idx in arrays.week_slices.items()
    }
    booked_hash = add("BOOKED", booked_dm, phase=0, parent=None)

    active = {x["name"]: x for x in protocol.active_scenarios(purpose="evaluate")}

    # Response-only projected hindsight maps are shared by every training row.
    for response_name, row in active.items():
        ss = copy.copy(s)
        ss.alpha = float(row["alpha"])
        ss.h = float(row["h"])
        planning, _ = protocol.implementable_oracle_planning(arrays, ss)
        dm = {int(wk): np.asarray(planning[idx], float) for wk, idx in arrays.week_slices.items()}
        add(
            f"PROJECTED::{response_name}",
            dm,
            phase=1,
            parent="BOOKED",
        )

    # Diagonal policy maps first, so off-diagonal maps have a deterministic
    # same-policy warm parent available.
    policy_by_train = {
        name: _load_policies(root) for name, root in training_roots.items()
    }
    for train_name, root in training_roots.items():
        row = active[train_name]
        ss = copy.copy(s)
        ss.alpha = float(row["alpha"])
        ss.h = float(row["h"])
        for method, weights in policy_by_train[train_name].items():
            dm, _ = evaluation._policy_meta(method, weights, arrays, ss)
            add(
                f"POLICY::{train_name}::{train_name}::{method}",
                dm,
                phase=1,
                parent="BOOKED",
            )

    for train_name, root in training_roots.items():
        for response_name, row in active.items():
            if response_name == train_name:
                continue
            ss = copy.copy(s)
            ss.alpha = float(row["alpha"])
            ss.h = float(row["h"])
            for method, weights in policy_by_train[train_name].items():
                dm, _ = evaluation._policy_meta(method, weights, arrays, ss)
                add(
                    f"POLICY::{train_name}::{response_name}::{method}",
                    dm,
                    phase=2,
                    parent=f"POLICY::{train_name}::{train_name}::{method}",
                )

    # Convert parent aliases to canonical hashes after all aliases exist.
    for h, row in meta.items():
        parent_alias = row.pop("parent_alias", None)
        row["parent_hash"] = None if parent_alias is None else alias_to_hash[parent_alias]
        row["aliases"] = sorted(set(row["aliases"]))
    if alias_to_hash["BOOKED"] != booked_hash:
        raise AssertionError("BOOKED hash changed during registry construction")
    return unique, meta, alias_to_hash


