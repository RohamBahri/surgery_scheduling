def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    experiment_root = Path(args.experiment_root).resolve()
    matrix_root = experiment_root / "holdout_matrix"

    if not protocol.tracked_tree_clean():
        raise RuntimeError("Matrix evaluation requires a clean tracked tree")

    # Install the exact same adapter/scientific/numeric stack before any
    # verification or solve. The supported wrapper import also installs the
    # non-destructive resilience layer through experiment_audit.
    final.install_final_adapter()
    fixes.apply_runtime_fixes()
    science.apply_scientific_fixes()
    shared.install_spawn_safe_weekly_logging()
    protocol.install_numeric_policy()
    protocol.install_behavioral_protocol()
    release.install_reviewed_guards()

    roots = _training_roots_from_seal(experiment_root)
    _verify_before_holdout(experiment_root, roots)
    seal_sha = _start_or_resume(
        experiment_root, matrix_root, roots, resume=bool(args.resume)
    )

    primary_name = next(
        x["name"] for x in protocol.active_scenarios(purpose="train") if x.get("role") == "primary"
    )
    primary_root = roots[primary_name]
    s = _load_settings(primary_root, matrix_root, args.data, args.cores)

    # Verify the physical workbook before loading/materializing the holdout.
    data_path = Path(args.data).resolve()
    freeze = _json(primary_root / "DATA_FREEZE.json")
    if base.sha256_file(data_path) != freeze["input_sha256"]:
        raise RuntimeError("Evaluation workbook hash differs from frozen Stage-1 workbook")

    base.setup_logging(matrix_root, bool(s.verbose))
    _write_json(
        matrix_root / "MATRIX_EVALUATION_SETTINGS.json",
        {
            "engine_version": ENGINE_VERSION,
            "git_head": protocol.git_head(),
            "seal_sha256": seal_sha,
            "amendment_sha256": protocol.amendment_hash(),
            "cores": int(s.cores),
            "solver_protocol": _solver_protocol(s),
            "execution": {
                "global_week_pool": True,
                "exact_duration_deduplication": True,
                "checkpoint_every_completed_week_map": True,
                "common_booked_warm_start": True,
                "offdiagonal_same_policy_diagonal_warm_start": True,
                "strong_exact_stage2_formulation": True,
            },
        },
    )

    try:
        weeks, arrays, scope_summary, split_audit = _materialize_holdout(primary_root, s)
        split_audit.to_csv(matrix_root / "WEEK_SPLIT.csv", index=False)
        _write_json(matrix_root / "SCOPE_SUMMARY.json", asdict(scope_summary))

        pre = _precompute(
            matrix_root,
            weeks,
            arrays,
            roots,
            s,
            seal_sha256=seal_sha,
        )
        base.LOG.info(
            "[MATRIX] precompute complete | requested_maps=%d unique_maps=%d dedup=%d",
            pre["total_requested_duration_maps"],
            pre["unique_duration_maps"],
            pre["exact_deduplications"],
        )

        _report_all(
            experiment_root,
            matrix_root,
            roots,
            data=args.data,
            cores=int(s.cores),
            seal_sha256=seal_sha,
        )
        _finish(experiment_root, matrix_root, roots, seal_sha256=seal_sha)
        base.LOG.info("[DONE] pooled checkpointed holdout matrix evaluation complete")
    except Exception as exc:
        _write_json(
            matrix_root / "RUN_STATUS.json",
            {
                "status": "FAILED_RESTARTABLE",
                "engine_version": ENGINE_VERSION,
                "error": repr(exc),
                "traceback": traceback.format_exc(),
                "seal_sha256": seal_sha,
                "amendment_sha256": protocol.amendment_hash(),
            },
        )
        base.LOG.exception("Matrix evaluation failed; completed checkpoints are preserved: %s", exc)
        raise

    _write_json(
        matrix_root / "RUN_STATUS.json",
        {
            "status": "HOLDOUT_MATRIX_EVALUATION_COMPLETE",
            "engine_version": ENGINE_VERSION,
            "seal_sha256": seal_sha,
            "amendment_sha256": protocol.amendment_hash(),
            "active_scenarios": list(roots),
        },
    )


if __name__ == "__main__":
    main()
