#!/usr/bin/env python3
"""Single-pass, checkpointed holdout matrix evaluation.

This runner is the supported efficient Stage-2 path after the experiment is
sealed.  It preserves the registered evaluation target (same mathematical
fixed-capacity planner, 1200 deterministic WorkLimit/site, 5e-4 native-Psi
MIP gap, one thread, fixed seed) while removing avoidable repeated work:

* load/materialize the holdout once;
* solve the realized oracle once for the whole experiment;
* solve BOOKED once;
* deduplicate exact duration maps across rows/response conditions;
* solve all remaining week-level jobs through one global process pool instead
  of restarting a 22-week pool for every method/condition;
* use a mathematically equivalent strengthened fixed-capacity formulation for
  Stage 2 only (continuous occupation variables plus x<=u links);
* use deterministic predecision warm starts: BOOKED for diagonal/projected
  solves and the same policy's diagonal schedule for off-diagonal response
  conditions;
* checkpoint every completed week/map so interruption never discards completed
  optimization work;
* replay the cached plans through the already-reviewed Stage-2 reporting code,
  so the paper outputs/metrics are generated by the same evaluation routines.

The strengthened formulation has the identical integer feasible assignments and
objective as src.solvers.fixed_capacity.solve_fixed_capacity_assignment.  With
binary x, constraints x[i,b] <= u[b] and u[b] <= sum_i x[i,b], 0<=u<=1 force
u[b] to equal the occupied-block indicator exactly.  Relative to the original
big-M occupation link this only strengthens the LP relaxation and removes
unnecessary binary u variables.
"""
